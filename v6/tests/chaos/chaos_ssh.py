#!/usr/bin/env python3
"""chaos_ssh.py — programmable fake `ssh` for WRE v6 chaos-matrix tests.

Placed on PATH (shim dir prepended) so `v6.controller.targets.Target.ssh_args`
(literal "ssh") resolves here instead of the real ssh. Zero network: the fake
speaks the rpc-stdio loop protocol on stdin/stdout and injects scripted
transport death modes. Both controller links are exercised through it:
  - one-shot `client.call_request` (subprocess.run)
  - `client.Session` (subprocess.Popen, loop mode)

Determinism contract:
  - behavior selected by CHAOS_MODE + CHAOS_PARAMS (JSON) only;
  - any generated bytes come from random.Random(CHAOS_SEED) (fixed seed);
  - cross-process state (connect/request counters) lives in CHAOS_STATE_DIR
    as append-only logs — counter-based, never wall-clock-based.

Observability files (in CHAOS_STATE_DIR):
  - connects.log   one line per process start: the argv (payloads must never
                   appear in argv — the matrix asserts on this)
  - requests.log   one compact JSON line per request RECEIVED, before any
                   response/failure — this is the peer-side execution counter
                   used by the E3 (resend exactly once) / E4 (never auto-
                   resend) assertions.

Modes:
  ok                  loop; respond OK (echo request id) to every request
  connect_refused     stderr message + exit 255, reads nothing (ssh connect failure)
  disconnect_on_read  read ONE request, log it, exit without responding
                      (params: exit_code=1, fail_first_n=1 — only the first
                      fail_first_n *process invocations* fail; later ones run ok)
  exit_after_n        serve params.n requests OK, then exit(1) mid-session
  delay               sleep params.delay_s before each response
  spin                read ONE request, log it, then never respond / never exit
                      (peer CPU-spin wedge; the client deadline must reap us)
  hang_forever        never read, never respond, never exit (negative control)
  truncate            read ONE request, write a partial JSON line (no newline),
                      flush, exit(1) (params: fail_first_n=1)
  garbage             first request -> one seeded garbage line; later requests OK
  bom_ok              respond with a BOM-prefixed valid JSON line
  banner_then_ok      print banner noise lines on STDOUT, then the JSON line
  duplicate           write the OK response line TWICE per request
  slow_drip           write the response params.chunk_bytes at a time with
                      params.chunk_delay_s sleeps between chunks
  stderr_flood        write params.flood_kb KiB to stderr, respond OK on stdout
  disk_full           respond ok=false errorClass=disk-full (structured peer error)
  storm_read_fail     every request: log, exit(1) without responding (every
                      invocation — reconnect-storm cell)

The shim itself must never crash ambiguously: unexpected internal errors print
to stderr and exit 3 so a harness bug is distinguishable from an injected fault.
"""

from __future__ import annotations

import json
import os
import random
import sys
import time

STATE_DIR = os.environ.get("CHAOS_STATE_DIR", "")
MODE = os.environ.get("CHAOS_MODE", "ok")
SEED = int(os.environ.get("CHAOS_SEED", "20260917"))


def _params() -> dict:
    try:
        return json.loads(os.environ.get("CHAOS_PARAMS", "{}"))
    except json.JSONDecodeError:
        return {}


PARAMS = _params()


def _append(name: str, line: str) -> None:
    if not STATE_DIR:
        return
    try:
        os.makedirs(STATE_DIR, exist_ok=True)
        with open(os.path.join(STATE_DIR, name), "a", encoding="utf-8") as fh:
            fh.write(line + "\n")
    except OSError:
        pass  # observability must never kill the scenario


def _connect_count() -> int:
    if not STATE_DIR:
        return 0
    try:
        with open(os.path.join(STATE_DIR, "connects.log"), encoding="utf-8") as fh:
            return sum(1 for _ in fh)
    except OSError:
        return 0


def _ok_line(req: dict, ordinal: int) -> str:
    return json.dumps({
        "id": req.get("id"),
        "ok": True,
        "protocolVersion": 6,
        "errorClass": "",
        "message": "",
        "data": {"echo": req.get("action"), "ordinal": ordinal,
                 "pid": os.getpid()},
    }, ensure_ascii=False) + "\n"


def _error_line(req: dict, error_class: str, message: str) -> str:
    return json.dumps({
        "id": req.get("id"),
        "ok": False,
        "protocolVersion": 6,
        "errorClass": error_class,
        "message": message,
        "data": {},
    }, ensure_ascii=False) + "\n"


def _garbage_line() -> str:
    rng = random.Random(SEED)
    kind = PARAMS.get("garbage_kind", "printable")
    n = int(PARAMS.get("garbage_len", 120))
    if kind == "braces":
        raw = "".join(rng.choice('{}[]",:0123truefalsn ') for _ in range(n))
    elif kind == "ctrl":
        raw = "".join(chr(rng.randrange(0x20, 0x2FFF)) for _ in range(n))
    else:
        import string
        raw = "".join(rng.choice(string.printable) for _ in range(n))
    # a "line" must never embed its own newline (that would split the frame)
    return raw.replace("\n", " ").replace("\r", " ")


def _read_requests():
    """Yield parsed request dicts from stdin until EOF; log each one."""
    ordinal = 0
    while True:
        line = sys.stdin.readline()
        if not line:
            return
        if not line.strip():
            continue  # blank keepalive, like the real native loop
        ordinal += 1
        try:
            req = json.loads(line)
        except json.JSONDecodeError:
            req = {"id": None, "action": "<unparseable>"}
        _append("requests.log", json.dumps(
            {"ordinal": ordinal, "pid": os.getpid(),
             "id": req.get("id"), "action": req.get("action")},
            ensure_ascii=False))
        yield req, ordinal


def _write_stdout(text: str) -> None:
    sys.stdout.write(text)
    sys.stdout.flush()


def _stderr_flood(kb: int) -> None:
    chunk = "chaos-stderr-noise " * 50  # ~950 bytes
    remaining = kb * 1024
    while remaining > 0:
        try:
            sys.stderr.write(chunk)
            sys.stderr.flush()
        except BrokenPipeError:
            return
        remaining -= len(chunk)


def _spin_forever() -> None:
    while True:
        time.sleep(3600)


def main() -> int:
    _append("connects.log", json.dumps({"argv": sys.argv, "pid": os.getpid()}))

    if MODE == "connect_refused":
        sys.stderr.write("ssh: connect to host 192.0.2.1 port 22: Connection refused\n")
        return 255

    if MODE == "hang_forever":
        _spin_forever()

    if MODE == "connect_refused_after_hello":
        _read_requests().__next__()  # consume one request, then die
        return 255

    requests = _read_requests()

    if MODE == "ok":
        for req, ordinal in requests:
            _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "disconnect_on_read":
        fail_first_n = int(PARAMS.get("fail_first_n", 1))
        if _connect_count() <= fail_first_n:
            for _req, _ordinal in requests:
                return int(PARAMS.get("exit_code", 1))  # logged, never answered
            return 0
        for req, ordinal in requests:
            _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "exit_after_n":
        n = int(PARAMS.get("n", 1))
        for req, ordinal in requests:
            _write_stdout(_ok_line(req, ordinal))
            if ordinal >= n:
                # idle-phase death: exit right after the nth ANSWERED request
                return int(PARAMS.get("exit_code", 1))
        return 0

    if MODE == "delay":
        delay_s = float(PARAMS.get("delay_s", 1.0))
        for req, ordinal in requests:
            time.sleep(delay_s)
            _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "spin":
        for _req, _ordinal in requests:
            _spin_forever()  # answered nothing; wedge after first request
        return 0

    if MODE == "truncate":
        fail_first_n = int(PARAMS.get("fail_first_n", 1))
        for req, ordinal in requests:
            if _connect_count() <= fail_first_n and ordinal == 1:
                full = _ok_line(req, ordinal)
                cut = int(PARAMS.get("cut_at", max(4, len(full) // 2)))
                _write_stdout(full[:cut])  # partial frame, no newline
                return 1
            _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "garbage":
        for req, ordinal in requests:
            if ordinal == 1:
                _write_stdout(_garbage_line() + "\n")
            else:
                _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "bom_ok":
        for req, ordinal in requests:
            _write_stdout("\ufeff" + _ok_line(req, ordinal))
        return 0

    if MODE == "banner_then_ok":
        for req, ordinal in requests:
            _write_stdout("OpenSSH_9.9p1 chaos-banner: MOTD noise line 1\n")
            _write_stdout("warning: something benign happened on the host\n")
            _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "duplicate":
        for req, ordinal in requests:
            line = _ok_line(req, ordinal)
            _write_stdout(line)
            _write_stdout(line)  # the duplicate frame the client must not misalign
        return 0

    if MODE == "slow_drip":
        chunk_bytes = int(PARAMS.get("chunk_bytes", 8))
        chunk_delay_s = float(PARAMS.get("chunk_delay_s", 0.05))
        for req, ordinal in requests:
            line = _ok_line(req, ordinal)
            for i in range(0, len(line), chunk_bytes):
                _write_stdout(line[i:i + chunk_bytes])
                time.sleep(chunk_delay_s)
        return 0

    if MODE == "stderr_flood":
        flood_kb = int(PARAMS.get("flood_kb", 64))
        for req, ordinal in requests:
            _stderr_flood(flood_kb)
            _write_stdout(_ok_line(req, ordinal))
        return 0

    if MODE == "disk_full":
        for req, _ordinal in requests:
            _write_stdout(_error_line(req, "disk-full",
                                      "No space left on device (chaos shim)"))
        return 0

    if MODE == "storm_read_fail":
        for _req, _ordinal in requests:
            return 1
        return 0

    sys.stderr.write(f"chaos_ssh: unknown CHAOS_MODE {MODE!r}\n")
    return 3


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BrokenPipeError:
        # the controller died first — that is the scenario, not a shim bug
        os._exit(0)
    except SystemExit:
        raise
    except Exception as exc:  # noqa: BLE001 - distinguish harness bugs from faults
        sys.stderr.write(f"chaos_ssh internal error: {type(exc).__name__}: {exc}\n")
        os._exit(3)
